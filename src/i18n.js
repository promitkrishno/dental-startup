const listeners = new Set();
let current = 'en';

try {
  const saved = localStorage.getItem('zw-lang');
  current = saved === 'en' || saved === 'de' ? saved : navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
} catch {
  current = 'en';
}

export function lang() {
  return current;
}

export function t(key, vars = {}) {
  const template = dictionary[current]?.[key] ?? dictionary.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

export function onLanguageChange(callback) {
  listeners.add(callback);
  return () => listeners.delete(callback);
}

export function applyStaticTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    node.setAttribute('aria-label', t(node.dataset.i18nAria));
  });
}

export function setLang(next) {
  if (next !== 'en' && next !== 'de') return;
  current = next;
  document.documentElement.lang = next;
  try { localStorage.setItem('zw-lang', next); } catch { /* storage unavailable */ }
  applyStaticTranslations();
  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === next));
  });
  listeners.forEach((callback) => callback(next));
}

export function initI18n() {
  document.documentElement.lang = current;
  applyStaticTranslations();
  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === current));
    button.addEventListener('click', () => setLang(button.dataset.lang));
  });
}
